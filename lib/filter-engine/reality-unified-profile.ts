/** Shared *authoring and scheduling* contract for video, camera and live.
 * Not a claim that every effect has a complete runtime on every platform.
 * Every mode starts identity-preserving; no ethnicity/age/beauty scoring.
 */
export const REALITY_UNIFIED_VERSION=1 as const
export type RealityMediaMode='camera'|'recorded-video'|'live-preview'
export type RealityDeviceClass='low'|'mid'|'high'|'desktop'
export type RealityLook='original'|'natural-light'|'studio-glow'
export type RealityGeometryPolicy='adaptive'|'high-quality-preview'
export type RealityUnifiedConfig=Readonly<{
 schemaVersion:1
 look:RealityLook
 geometryPolicy:RealityGeometryPolicy
 /** Every anatomical morph/beauty slider needs an affirmative user action. */
 faceShapeOptIn:boolean
 faceMorphStrength:number
 skinSmoothing:number
}>
export type RealitySharedSession=Readonly<{
 mode:RealityMediaMode
 studio:StudioState
 mesh:RealityMeshBudget
 warnings:readonly string[]
}>
export type RealityMeshBudget=Readonly<{
 /** The dense 478-landmark mesh is not itself a million measured face points. */
 baseTriangles:number
 /** Virtual / target draw budget. A million triangle representation is NOT
  * generated by this planning function and cannot invent face detail. */
 targetTriangles:number
 trianglesPerBaseFace:number
 refinementFactor:number
 tier:RealityDeviceClass
 measuredFps:number|null
 trackingValid:boolean
 extraDenseEnabled:boolean
}>
export const DEFAULT_REALITY_UNIFIED_CONFIG:RealityUnifiedConfig=Object.freeze({
 schemaVersion:1,look:'original',geometryPolicy:'adaptive',
 faceShapeOptIn:false,faceMorphStrength:0,skinSmoothing:0,
})
const finite=(n:number)=>Number.isFinite(n)
const clamp=(v:number,min:number,max:number)=>
 finite(v)?Math.min(max,Math.max(min,v)):min
const profiles:Readonly<Record<RealityDeviceClass,number>>={
 low:6000,mid:24000,high:96000,desktop:240000,
}
/** Backend-independent status; applies to any entry in the unified registry. */
export function realityEffectCompatibility(
 id:string,mode:RealityMediaMode,
):Readonly<{
 manifest:RealityEffectManifest|null
 catalogued:boolean
 mode:RealityMediaMode
 support:'shared-definition-only'|'unsupported'
}>{
 const manifest=getRealityEffect(id)
 return {manifest,catalogued:!!manifest,mode,
  support:manifest?'shared-definition-only':'unsupported'}
}

/** A *budget* for future GPU tessellation/LOD; never allocate >1M blindly.
 * Face fitting uses 468/478 inferred points independently of visual LOD.
 * With tracked faces, FPS and device class cap the desired visualization cost.
 */
export function planRealityMeshBudget(options:Readonly<{
 mode:RealityMediaMode;device:RealityDeviceClass
 baseTriangles?:number;fps?:number|null
 trackingValid:boolean;quality:'adaptive'|'high-quality-preview'
 optInUltra?:boolean
}>):RealityMeshBudget{
 const base=options.baseTriangles??912
 if(!Number.isSafeInteger(base)||base<1||base>30000)
  throw Error('reality_invalid_base_mesh_triangles')
 const fps=options.fps
 const measured=typeof fps==='number'&&finite(fps)&&fps>0&&fps<=240?fps:null
 const isRealtime=options.mode!=='recorded-video'
 const targetFps=isRealtime?30:24
 let limit=profiles[options.device]
 // A playback editing session may spend more resources than a live broadcaster.
 if(!isRealtime&&options.quality==='high-quality-preview')limit*=2
 // Only an explicit desktop-level, smooth, verified test can request 1M in live.
 const ultra=options.optInUltra===true&&options.device==='desktop'&&
  options.quality==='high-quality-preview'&&
  measured!==null&&measured>=55&&options.trackingValid
 if(ultra)limit=1_048_576
 // Downshift conservatively at startup or if the measured frame rate drops.
 if(measured!==null&&measured<targetFps*.8)limit=Math.floor(limit*.25)
 else if(measured!==null&&measured<targetFps)limit=Math.floor(limit*.5)
 if(!options.trackingValid)limit=base
 // For a regular triangular mesh, subdivision multiplies by 4 per level.
 // These are *theoretical* LOD targets, not a geometry allocation.
 let refinement=1
 while(base*refinement*4<=limit)refinement*=4
 return {
  baseTriangles:base,targetTriangles:base*refinement,
  trianglesPerBaseFace:refinement,
  refinementFactor:Math.sqrt(refinement),
  tier:options.device,measuredFps:measured,
  trackingValid:options.trackingValid,
  extraDenseEnabled:ultra&&refinement>256,
 }
}

/** Shared profile transforms only the already supported StudioState parameters.
 * Original mode is a precise visual no-op; no automatic face shrinking.
 */
export function resolveUnifiedRealityLook(
 config:RealityUnifiedConfig,
 previous:StudioState=createStudioState(),
):StudioState{
 if(config.schemaVersion!==1||
  !['original','natural-light','studio-glow'].includes(config.look)|| 
  !['adaptive','high-quality-preview'].includes(config.geometryPolicy))
  throw Error('reality_unified_invalid_config')
 const result:StudioState={
  ...previous,
  color:{...previous.color},
  beauty:{...previous.beauty},
  effects:{...previous.effects},
  face:{...previous.face},
 }
 if(config.look==='natural-light'){
  result.color.exposure=clamp(result.color.exposure+.06,-1,1)
  result.color.highlights=clamp(result.color.highlights-.09,-1,1)
  result.color.shadows=clamp(result.color.shadows+.08,-1,1)
  result.color.vibrance=clamp(result.color.vibrance+.05,-1,1)
 }else if(config.look==='studio-glow'){
  result.color.exposure=clamp(result.color.exposure+.08,-1,1)
  result.color.highlights=clamp(result.color.highlights-.12,-1,1)
  result.color.shadows=clamp(result.color.shadows+.07,-1,1)
  result.color.glow=clamp(result.color.glow+.12,0,1)
 }
 // When opt-in is absent there is no deformation, whitening or assumed "ideal" face.
 if(config.faceShapeOptIn){
  result.beauty.smooth=clamp(config.skinSmoothing,0,.35)
  if(config.faceMorphStrength>0){
   result.face={id:'face-morph',strength:clamp(config.faceMorphStrength,0,.45),
    morph:{...DEFAULT_FACE_MORPH,strength:clamp(config.faceMorphStrength,0,.45)}}
  }
 }
 return result
}
export function makeUnifiedRealitySession(options:Readonly<{
 mode:RealityMediaMode;device:RealityDeviceClass
 config:RealityUnifiedConfig;studio?:StudioState
 measuredFps?:number|null;trackingValid:boolean
}>):RealitySharedSession{
 const studio=resolveUnifiedRealityLook(options.config,options.studio)
 const mesh=planRealityMeshBudget({
  mode:options.mode,device:options.device,
  fps:options.measuredFps??null,trackingValid:options.trackingValid,
  quality:options.config.geometryPolicy,
 })
 const warnings:string[]=[]
 if(!options.trackingValid)warnings.push('tracking_missing_no_3d_claims')
 if(!options.config.faceShapeOptIn)warnings.push('face_geometry_unchanged')
 warnings.push('all_effects_not_yet_runtime_parity_certified')
 return {mode:options.mode,studio,mesh,warnings}
}
