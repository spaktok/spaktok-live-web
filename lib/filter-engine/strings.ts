const dictionaries: Partial<Record<string, Record<Key, string>>> = { en, ar }

export function useStudioStrings() {
  const { language } = useLanguage()
  const dictionary = dictionaries[language] ?? en
  return { s: (key: Key) => dictionary[key] ?? en[key], language }
}

export type StudioStringKey = Key
